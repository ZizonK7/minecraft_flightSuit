package com.pfkfks.flightsuit.client.parts;

import com.pfkfks.flightsuit.FlightSuitMod;
import com.pfkfks.flightsuit.planet.dbz.DbzFighterEntity;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

import java.util.List;

/**
 * M18 head parts: the Namekians' two antennae and pointed ears (Piccolo, Dende), Ginyu's horns, Dodoria's head spikes.
 * Groups under the head: {@code antennae}, {@code ears}, {@code horns}, {@code spikes}.
 *
 * Boxes, UVs and textures/entity/dbz/parts/namekian.png come from tools/ModelGen.java (parts_namekian).
 */
public class NamekianParts extends DbzPartsModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(FlightSuitMod.MODID, "parts_namekian"), "main");
    private static final ResourceLocation TEXTURE = new ResourceLocation(FlightSuitMod.MODID, "textures/entity/dbz/parts/namekian.png");
    public static final List<String> GROUPS = List.of("antennae", "ears", "horns", "spikes");

    public NamekianParts(ModelPart root) {
        super(root);
    }

    @Override
    public ResourceLocation texture() {
        return TEXTURE;
    }

    @Override
    public List<String> groups() {
        return GROUPS;
    }

    @Override
    public void animate(DbzFighterEntity fighter, float ageInTicks) {
        ModelPart antennae = group("antennae");
        if (antennae != null) {
            // A slight bob with the step.
            antennae.xRot = Mth.sin(ageInTicks * 0.3F) * 0.04F;
        }
    }

    // <ModelGen:parts_namekian>
    // Generated by tools/ModelGen.java - edit the layout there, not here.
    public static LayerDefinition createLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition head = root.addOrReplaceChild("head", CubeListBuilder.create(),
                PartPose.offset(0.0F, 0.0F, 0.0F));
        head.addOrReplaceChild("antennae", CubeListBuilder.create()
                .texOffs(20, 0).addBox(1.0F, -3.0F, -1.0F, 1.0F, 3.0F, 1.0F) // left
                .texOffs(24, 0).addBox(-2.0F, -3.0F, -1.0F, 1.0F, 3.0F, 1.0F), // right
                PartPose.offset(0.0F, -8.0F, -2.0F));
        head.addOrReplaceChild("ears", CubeListBuilder.create()
                .texOffs(8, 0).addBox(-5.0F, -2.0F, -1.0F, 1.0F, 3.0F, 2.0F) // ear_right
                .texOffs(14, 0).addBox(4.0F, -2.0F, -1.0F, 1.0F, 3.0F, 2.0F), // ear_left
                PartPose.offset(0.0F, -4.0F, 0.0F));
        head.addOrReplaceChild("horns", CubeListBuilder.create()
                .texOffs(28, 0).addBox(-4.0F, -3.0F, -1.0F, 1.0F, 3.0F, 1.0F) // horn_right
                .texOffs(32, 0).addBox(3.0F, -3.0F, -1.0F, 1.0F, 3.0F, 1.0F), // horn_left
                PartPose.offset(0.0F, -8.0F, 0.0F));
        head.addOrReplaceChild("spikes", CubeListBuilder.create()
                .texOffs(0, 0).addBox(-1.0F, -3.0F, -1.0F, 2.0F, 3.0F, 2.0F), // spike
                PartPose.offset(0.0F, -8.0F, 0.0F));
        root.addOrReplaceChild("body", CubeListBuilder.create(),
                PartPose.offset(0.0F, 0.0F, 0.0F));
        return LayerDefinition.create(mesh, 64, 32);
    }
    // </ModelGen:parts_namekian>
}
