package com.pfkfks.flightsuit.client.parts;

import com.pfkfks.flightsuit.FlightSuitMod;
import com.pfkfks.flightsuit.planet.dbz.DbzFighterEntity;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

import java.util.List;

/**
 * M18 Cell's and Buu's parts: Cell's head crest in each form (imperfect, semi-perfect, perfect, the Cell Jr.), his
 * wings and the imperfect form's tail; Buu's head antenna (fat, super, kid). Groups: {@code crest_imperfect},
 * {@code crest_semi}, {@code crest}, {@code crest_jr}, {@code antenna_fat}, {@code antenna_super}, {@code antenna_kid}
 * under the head; {@code wings}, {@code tail} under the body.
 *
 * Boxes, UVs and textures/entity/dbz/parts/cell_buu.png come from tools/ModelGen.java (parts_cell_buu).
 */
public class CellBuuParts extends DbzPartsModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(FlightSuitMod.MODID, "parts_cell_buu"), "main");
    private static final ResourceLocation TEXTURE = new ResourceLocation(FlightSuitMod.MODID, "textures/entity/dbz/parts/cell_buu.png");
    public static final List<String> GROUPS = List.of("crest_imperfect", "crest_semi", "crest", "crest_jr", "wings", "tail", "antenna_fat", "antenna_super", "antenna_kid");

    public CellBuuParts(ModelPart root) {
        super(root);
    }

    @Override
    public ResourceLocation texture() {
        return TEXTURE;
    }

    @Override
    public List<String> groups() {
        return GROUPS;
    }

    @Override
    public void animate(DbzFighterEntity fighter, float ageInTicks) {
        ModelPart tail = group("tail");
        if (tail != null) {
            tail.yRot = Mth.sin(ageInTicks * 0.12F) * 0.3F;
            tail.xRot = 0.6F + Mth.sin(ageInTicks * 0.08F) * 0.1F;
        }
        for (String name : new String[]{"antenna_fat", "antenna_super", "antenna_kid"}) {
            ModelPart antenna = group(name);
            if (antenna != null) {
                antenna.zRot = Mth.sin(ageInTicks * 0.2F) * 0.08F;
            }
        }
        ModelPart wings = group("wings");
        if (wings != null && fighter.getAction() == com.pfkfks.flightsuit.planet.dbz.DbzAction.FLY) {
            wings.xRot = -0.3F + Mth.sin(ageInTicks * 0.4F) * 0.1F;
        } else if (wings != null) {
            wings.xRot = 0.0F;
        }
    }

    // <ModelGen:parts_cell_buu>
    // Generated by tools/ModelGen.java - edit the layout there, not here.
    public static LayerDefinition createLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition head = root.addOrReplaceChild("head", CubeListBuilder.create(),
                PartPose.offset(0.0F, 0.0F, 0.0F));
        head.addOrReplaceChild("crest_imperfect", CubeListBuilder.create()
                .texOffs(0, 12).addBox(-1.0F, -3.0F, -2.0F, 2.0F, 3.0F, 4.0F), // crest
                PartPose.offset(0.0F, -8.0F, 0.0F));
        head.addOrReplaceChild("crest_semi", CubeListBuilder.create()
                .texOffs(12, 12).addBox(-1.0F, -3.0F, -2.0F, 2.0F, 3.0F, 4.0F), // crest
                PartPose.offset(0.0F, -8.0F, 0.0F));
        head.addOrReplaceChild("crest", CubeListBuilder.create()
                .texOffs(24, 12).addBox(-1.0F, -3.0F, -2.0F, 2.0F, 3.0F, 4.0F), // crest
                PartPose.offset(0.0F, -8.0F, 0.0F));
        head.addOrReplaceChild("crest_jr", CubeListBuilder.create()
                .texOffs(52, 12).addBox(-1.0F, -2.0F, -1.0F, 2.0F, 2.0F, 3.0F), // crest
                PartPose.offset(0.0F, -8.0F, 0.0F));
        head.addOrReplaceChild("antenna_fat", CubeListBuilder.create()
                .texOffs(44, 12).addBox(-1.0F, -4.0F, -1.0F, 2.0F, 4.0F, 2.0F), // antenna
                PartPose.offset(0.0F, -8.0F, 0.0F));
        head.addOrReplaceChild("antenna_super", CubeListBuilder.create()
                .texOffs(52, 0).addBox(-1.0F, -6.0F, -1.0F, 2.0F, 6.0F, 2.0F), // antenna
                PartPose.offset(0.0F, -8.0F, 0.0F));
        head.addOrReplaceChild("antenna_kid", CubeListBuilder.create()
                .texOffs(36, 12).addBox(-1.0F, -5.0F, -1.0F, 2.0F, 5.0F, 2.0F), // antenna
                PartPose.offset(0.0F, -8.0F, 0.0F));
        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create(),
                PartPose.offset(0.0F, 0.0F, 0.0F));
        body.addOrReplaceChild("wings", CubeListBuilder.create()
                .texOffs(24, 0).addBox(-6.0F, 0.0F, 0.0F, 6.0F, 10.0F, 1.0F) // wing_right
                .texOffs(38, 0).addBox(0.0F, 0.0F, 0.0F, 6.0F, 10.0F, 1.0F), // wing_left
                PartPose.offset(0.0F, 1.0F, 2.0F));
        body.addOrReplaceChild("tail", CubeListBuilder.create()
                .texOffs(0, 0).addBox(-1.0F, -1.0F, 0.0F, 2.0F, 2.0F, 10.0F), // tail
                PartPose.offsetAndRotation(0.0F, 10.0F, 2.0F, 0.6F, 0.0F, 0.0F));
        return LayerDefinition.create(mesh, 64, 64);
    }
    // </ModelGen:parts_cell_buu>
}
