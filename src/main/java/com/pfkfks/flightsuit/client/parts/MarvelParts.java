    private static final ResourceLocation TEXTURE = new ResourceLocation(FlightSuitMod.MODID, "textures/entity/dbz/parts/marvel.png");
    public static final List<String> GROUPS = List.of("cape_doom", "cape_god", "cape_magneto", "cape_witch", "feathers");
    private static final String[] CAPES = {"cape_doom", "cape_god", "cape_magneto", "cape_witch"};
    /** Rest pose (x rotation) of the upper and lower panels - the same as ModelGen's MarvelParts.REST. */
    private static final float[] REST = {0.08F, 0.06F};

    public MarvelParts(ModelPart root) {
        super(root);
    }

    @Override
    public ResourceLocation texture() {
        return TEXTURE;
    }

    @Override
    public List<String> groups() {
        return GROUPS;
    }

    @Override
    public void animate(DbzFighterEntity fighter, float ageInTicks) {
        float speed = Math.min(1.0F, fighter.walkAnimation.speed());
        float flutter = Mth.sin(ageInTicks * 0.12F) * 0.03F + Mth.sin(ageInTicks * 0.37F) * 0.015F;
        float upper;
        float lower;
        switch (fighter.getAction()) {
            case FLY -> {
                // Streaming out behind, rippling.
                upper = 1.15F + Mth.sin(ageInTicks * 0.5F) * 0.06F;
                lower = 0.25F + Mth.sin(ageInTicks * 0.5F - 1.2F) * 0.12F;
            }
            case TRANSFORM, CHARGE, HANDS_UP -> {
                // Power rising: lifted and snapping.
                upper = 0.55F + Mth.sin(ageInTicks * 0.9F) * 0.08F;
                lower = 0.2F + Mth.sin(ageInTicks * 0.9F - 1.0F) * 0.1F;
            }
            case DOWN -> {
                upper = 0.0F;
                lower = 0.0F;
            }
            default -> {
                // Walking pushes it back a little; standing, a slow stir.
                upper = REST[0] + speed * 0.45F + flutter;
                lower = REST[1] + speed * 0.2F + flutter * 0.6F;
            }
        }
        for (String name : CAPES) {
            ModelPart cape = group(name);
            if (cape == null || !cape.visible) {
                continue;
            }
            cape.xRot = upper;
            if (cape.hasChild(name + "_low")) {
                cape.getChild(name + "_low").xRot = lower;
            }
        }
    }

